function [K,T,Pg]=assemble_Kreduce_structured_2D(S,eK_set,alpha,Phi)
% One unique upper 8x8 owner-pair product. Same 16 OvFEM Ke templates.
% No global element plan, local dense group stack, COO or scalar sparse.
g=gpuDevice;wait(g);started=tic;
assert(exist('mechanics2d_blocks_v1_cuda_mex','file')==3,'mechanics2d:Build','Run build_mechanics2d_cuda in a fresh MATLAB session.');
t=tic;ke=zeros(32,32,16);
for k=1:16,w=size(eK_set{k},1);ke(1:w,1:w,k)=eK_set{k};end
Pg=gpuArray(Phi);ag=gpuArray(double(alpha(:)));kg=gpuArray(ke);wait(g);upload=toc(t);
storage=class(Phi);if isa(Phi,'gpuArray'),storage=classUnderlying(Phi);end
t=tic;blocks=mechanics2d_blocks_v1_cuda_mex('assemble',Pg,ag,kg,double([S.nslx S.nsly S.nelxIs-1]));wait(g);projection=toc(t);
K=struct('format',"symmetric-upper-block8-structured",'blocks',blocks, ...
 'nC',8*S.ns,'nslx',S.nslx,'nsly',S.nsly,'block_size',8, ...
 'upper_offsets',[0 0;0 1;1 -1;1 0;1 1]);
T=struct('backend',"cuda-structured-unique-owner-pairs",'fallback',false,'fallback_reason',"", ...
 'used_gpu_accum',true,'used_cpu_accum',false,'upload',upload,'projection',projection, ...
 'indices',0,'sparse_merge',0,'t_total',toc(started),'dense_local_stiffness_created',false, ...
 'scalar_sparse_created',false,'scalar_coo_created',false,'global_element_plan_created',false, ...
 'coefficient_precision',"FP64",'basis_storage_precision',string(storage), ...
 'matrix_device',"gpu",'operator_bytes',8*numel(blocks),'stored_upper_block_slots',5*S.ns, ...
 'valid_upper_blocks',S.ns+S.nslx*(S.nsly-1)+(S.nslx-1)*(3*S.nsly-2), ...
 'timing_scope',"Synchronized host packing/upload and unique-owner-pair kernel wall times; no hidden topology-plan or sparse conversion.");
end
